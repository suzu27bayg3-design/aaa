def lake(t, lt):
    """湖の北側を広く見せてから、入り江に寄る。入り江に光の輪"""
    k = min(1.0, lt / 4.5)
    c = (C0[0] + (BAY[0] - C0[0]) * k, C0[1] + (BAY[1] - C0[1]) * k)
    return A.ring(lt, t, c, at=BAY, scale=1.6 - 0.65 * k, color=(170, 255, 170), size=150)


def wave(t, lt):
    """風の波が湖をわたって入り江へ（光の粒）"""
    return A.flow(lt, t, (900, 900), WAVE, scale=1.6, color=(200, 240, 255), speed=110, spread=35, dark=0.8, size=5)


def bay(t, lt):
    return A.ring(lt, t, BAY, at=BAY, scale=1.0, color=(170, 255, 170), size=190)


