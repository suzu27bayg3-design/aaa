def _label(d, xy, s, size=34, fill=L.WHITE):
    d.text(xy, s, font=L.jp(size, True), fill=fill, anchor="mm", stroke_width=5,
           stroke_fill=L.WHITE if fill == L.NAVY else L.NAVY)


def origin(t, lt):
    """海の断面：海底火山（海山）の上のサンゴ礁が、プレートに乗って日本の方へ運ばれる"""
    W, H = 900, 640
    im = Image.new("RGBA", (W, H))
    d = ImageDraw.Draw(im)
    d.rectangle((0, 120, W, 470), fill=(40, 90, 170))  # 海
    d.rectangle((0, 470, W, 560), fill=(110, 80, 60))  # プレート
    d.polygon([(760, 120), (W, 120), (W, 560), (820, 560)], fill=(90, 150, 80))  # 日本（陸）
    _label(d, (840, 90), "日本", 34)
    k = min(1.0, lt / 5.0)
    sx = 120 + 520 * k
    d.polygon([(sx - 130, 470), (sx, 230), (sx + 130, 470)], fill=(60, 50, 50))  # 海山
    d.polygon([(sx - 55, 270), (sx - 20, 215), (sx + 20, 215), (sx + 55, 270)], fill=(245, 240, 225))  # サンゴ礁の石灰岩
    for i in range(6):
        x = 60 + i * 130 + (t * 60) % 130
        d.line((x, 515, x + 50, 515), fill=(255, 220, 120), width=6)
        d.polygon([(x + 50, 505), (x + 70, 515), (x + 50, 525)], fill=(255, 220, 120))
    _label(d, (sx, 185), "サンゴ礁 → 石灰岩", 30)
    _label(d, (300, 590), "プレートに乗って運ばれる（約3億年前〜）", 32, (255, 220, 120))
    return im


def dissolve(t, lt):
    """雨が二酸化炭素をとかして弱い酸になり、石灰岩の割れ目を少しずつ広げる"""
    W, H = 900, 640
    im = Image.new("RGBA", (W, H))
    d = ImageDraw.Draw(im)
    d.rectangle((40, 220, W - 40, 560), fill=LIME)
    k = min(1.0, lt / 5.0)
    for x in (200, 450, 700):
        w = 4 + 34 * k
        d.polygon([(x - w, 220), (x + w, 220), (x + w * 0.3, 560), (x - w * 0.3, 560)], fill=(60, 70, 90))
        if k > 0.1:
            d.line((x, 230, x, 230 + 300 * k), fill=WATER, width=6)
    for i in range(14):  # 雨
        x = 60 + i * 60
        y = 40 + ((t * 300 + i * 53) % 170)
        d.line((x, y, x - 6, y + 22), fill=(170, 210, 255), width=4)
    _label(d, (W / 2, 30), "雨 ＋ 二酸化炭素 → 弱い酸", 34)
    _label(d, (W / 2, 600), "割れ目から、石灰岩を少しずつ溶かす", 34, (255, 220, 120))
    return im


def cave(t, lt):
    """横から見た台地：割れ目がつながって地下の川になり、空洞がだんだん大きくなる"""
    W, H = 900, 640
    im = Image.new("RGBA", (W, H))
    d = ImageDraw.Draw(im)
    d.rectangle((40, 140, W - 40, 560), fill=LIME)
    for x in (180, 430, 690):  # 地表のくぼみ（ドリーネ）
        d.ellipse((x - 70, 110, x + 70, 175), fill=(14, 22, 48))
    d.rectangle((40, 90, W - 40, 140), fill=(14, 22, 48))
    k = min(1.0, lt / 4.5)
    cx, cy = W / 2, 400
    rw, rh = 60 + 330 * k, 25 + 85 * k
    d.ellipse((cx - rw, cy - rh, cx + rw, cy + rh), fill=(30, 30, 40))
    d.rectangle((cx - rw * 0.9, cy + rh * 0.55, cx + rw * 0.9, cy + rh * 0.8), fill=WATER)
    _label(d, (cx, cy - 10), "地下の川", 32)
    _label(d, (W / 2, 600), "長い時間をかけて、大きな洞くつに", 34, (255, 220, 120))
    _label(d, (180, 70), "ドリーネ（くぼみ）", 28)
    return im


def drip(t, lt):
    """天井のしずくから二酸化炭素がぬけ、溶けていた石灰がまた固まる → つらら石と石筍がのびる"""
    W, H = 900, 640
    im = Image.new("RGBA", (W, H))
    d = ImageDraw.Draw(im)
    d.rectangle((40, 40, W - 40, 110), fill=LIME2)  # 天井
    d.rectangle((40, 530, W - 40, 590), fill=LIME2)  # 床
    k = min(1.0, lt / 4.5)
    for x, s in ((260, 1.0), (520, 0.7), (720, 0.85)):
        L1 = (60 + 180 * k) * s
        d.polygon([(x - 26 * s, 110), (x + 26 * s, 110), (x, 110 + L1)], fill=(235, 230, 215))
        L2 = (30 + 120 * k) * s
        d.polygon([(x - 34 * s, 530), (x + 34 * s, 530), (x, 530 - L2)], fill=(235, 230, 215))
        y = 110 + L1 + ((t * 220 + x) % max(1, 530 - L2 - 110 - L1))
        d.ellipse((x - 8, y - 12, x + 8, y + 8), fill=(170, 210, 255))
    for i in range(5):  # ぬけていく二酸化炭素
        x = 330 + i * 60
        y = 300 - ((t * 60 + i * 37) % 120)
        d.text((x, y), "CO2", font=L.jp(26, True), fill=(255, 255, 255, 200), anchor="mm")
    _label(d, (260, 470), "石筍", 30)
    _label(d, (720, 330), "つらら石", 30)
    _label(d, (W / 2, 620), "CO2がぬける → 石灰がまた固まる（②の逆）", 32, (255, 220, 120))
    return im


