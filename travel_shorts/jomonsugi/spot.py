PINK = np.array([255, 120, 190.])


def _r(tex, az, el, dist, target=C):
    return T3.render(_DEM, tex, _MPP, target, az=az, el=el, dist=dist, exag=2.0, size=(540, 960),
                     fill_gaps=True).resize((SW, SH), Image.BICUBIC)


def island(t, lt):
    """海から一気にそびえる屋久島を、ゆっくり回りこむ"""
    return _r(_TEX, az=160 + 4 * lt, el=10, dist=27000 - 400 * lt)


def granite(t, lt):
    """島の大部分をしめる花崗岩の範囲を、地質図からピンクで光らせる"""
    k = min(1.0, lt / 2.0)
    a = (0.3 + 0.08 * math.sin(t * 3)) * k
    tex = (_TEX * (1 - _GRA * a) + PINK * _GRA * a).astype(np.uint8)
    return _r(tex, az=175, el=14, dist=24000)


