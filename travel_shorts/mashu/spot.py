def hook(t, lt):
    return A.view(lt, LAKE, s0=1.0, s1=0.8, dur=4.5)


def river(t, lt):
    """湖のまわりをぐるっと光がなぞる（流れこむ大きな川も、流れ出る川もない）"""
    import math
    from PIL import Image, ImageDraw
    b, im = A.frame(LAKE, 0.85)
    lay = Image.new("RGB", im.size)
    d = ImageDraw.Draw(lay)
    k = min(1.0, lt / 2.5)
    pts = []
    for i in range(int(120 * k) + 2):
        a = 2 * math.pi * i / 120 - math.pi / 2
        pts.append(A.scr(b, LAKE[0] + 205 * math.cos(a), LAKE[1] + 240 * math.sin(a)))
    d.line(pts, fill=(140, 220, 255), width=8, joint="curve")
    return A.glow(im, lay)


