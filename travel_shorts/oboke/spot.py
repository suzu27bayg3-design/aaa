RIVER = [(1500, 1250), (1400, 1150), (1350, 1050), (1250, 950), (1120, 850), (1068, 700), (1028, 520), (960, 300), (942, 150)]  # 上流（南）→下流（北）
C = (1150, 750)
WATER = (150, 230, 255)


def river(t, lt):
    """吉野川にそって、上流（南）から下流（北）へ光の粒が流れる"""
    s = 1.0 + 0.3 * min(1, lt / 4)
    return A.flow(lt, t, C, RIVER, scale=s, color=WATER, speed=90, spread=4, dark=0.95, size=5)


def geo(t, lt):
    """航空写真の上に、地質図を半分すかして重ねる。川はそのまま光らせる"""
    k = min(1.0, lt / 2.0)
    fl = A.flow(lt, t, C, RIVER, scale=1.3, color=WATER, speed=90, spread=4, dark=1.0, size=5)
    b = A.box(C, 1.3)
    g = GEO.crop(tuple(int(v) for v in b)).resize((SW, SH), Image.BILINEAR)
    return Image.blend(fl, g, 0.5 * k)


def deep(t, lt):
    """川に寄っていく（谷をほり下げる）"""
    k = min(1.0, lt / 4.5)
    s = 1.3 - 0.6 * k
    c = (C[0] + (1040 - C[0]) * k, C[1] + (520 - C[1]) * k)
    return A.flow(lt, t, c, RIVER, scale=s, color=WATER, speed=60, spread=3, dark=0.95, size=5)


