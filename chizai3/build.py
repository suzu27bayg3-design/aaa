def kana(i, n):
    return "アイウエオ"[i] if n > 2 else ""


def build():
    for s in SETS:
        s["url"] = REPO_BLOB + f"set-{s['id']}.md"
        for i, q in enumerate(s["questions"], 1):
            q["n"] = i
    # HTML
    tpl = (HERE / "drill_template.html").read_text(encoding="utf-8")
    data = json.dumps(SETS, ensure_ascii=False).replace("</", "<\\/")
    (HERE / "drill.html").write_text(tpl.replace("/*__SETS__*/[]", data), encoding="utf-8")
    # Markdown
    for s in SETS:
        out = [f"# 知財検定3級 法令ドリル セット {s['id']}：{s['topic']}", "",
               f"[← 一覧に戻る](README.md)", "", "## この分野の原理", "", s["principle"], ""]
        if s.get("scenario"):
            out += ["## 事例", "", s["scenario"], ""]
        for q in s["questions"]:
            out += [f"## 問{q['n']}　{q['topic']}", "", q["ask"], ""]
            n = len(q["choices"])
            for i, c in enumerate(q["choices"]):
                out.append(f"- {kana(i, n)} {c}" if n > 2 else f"- {c}")
            ans = q["choices"][q["answer"] - 1] if n == 2 else kana(q["answer"] - 1, n)
            out += ["", "<details><summary>▶ 解答・解説</summary>", "", f"**正解：{ans}**", "", q["explain"], "", "</details>", ""]
        (HERE / f"set-{s['id']}.md").write_text("\n".join(out), encoding="utf-8")
    total = sum(len(s["questions"]) for s in SETS)
    print(f"sets={len(SETS)} questions={total}")


